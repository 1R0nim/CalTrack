package com.example.caltrack.ui.theme

import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.ui.unit.dp

// The theme keeps Material's default shapes: buttons morph between them when pressed or checked,
// and rounder theme shapes would flatten those morphs. Cards use these much rounder corners instead.
val HeroCardShape = RoundedCornerShape(40.dp)
val CardShape = RoundedCornerShape(32.dp)
val SmallCardShape = RoundedCornerShape(28.dp)
val ListItemShape = RoundedCornerShape(24.dp)
val FieldShape = RoundedCornerShape(16.dp)
